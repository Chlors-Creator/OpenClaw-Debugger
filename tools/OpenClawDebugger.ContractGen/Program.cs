using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;

namespace OpenClawDebugger.ContractGen;

/// <summary>
/// 跨平台的桥接契约生成器，替代原先只能跑在 Windows PowerShell 上的
/// Tools/Generate-BridgeContract.ps1。输出内容与旧脚本保持逐字等价：
///   shared/WebUi/bridge-contract.json      → 输入（唯一真源）
///   src/OpenClawDebugger.Core/Bridge/BridgeContractGenerated.cs
///   shared/WebUi/bridge-contract.generated.js
/// </summary>
internal static class Program
{
    private const string CSharpRelativePath = "src/OpenClawDebugger.Core/Bridge/BridgeContractGenerated.cs";
    private const string JavaScriptRelativePath = "shared/WebUi/bridge-contract.generated.js";
    private const string JsonRelativePath = "shared/WebUi/bridge-contract.json";

    private static int Main(string[] args)
    {
        try
        {
            var repoRoot = ResolveRepoRoot(args);
            var jsonPath = Path.Combine(repoRoot, JsonRelativePath);
            if (!File.Exists(jsonPath))
            {
                Console.Error.WriteLine($"找不到桥接契约：{jsonPath}");
                return 2;
            }

            var root = JsonNode.Parse(File.ReadAllText(jsonPath), documentOptions: new JsonDocumentOptions
            {
                AllowTrailingCommas = true,
                CommentHandling = JsonCommentHandling.Skip
            }) as JsonObject ?? throw new InvalidOperationException("桥接契约必须是 JSON 对象。");

            var protocolVersion = ReadProtocolVersion(root);
            var commands = root["commands"] as JsonObject
                ?? throw new InvalidOperationException("桥接协议必须包含 protocolVersion 和 commands。");

            var csharp = BuildCSharp(protocolVersion, commands);
            var javascript = BuildJavaScript(root);

            WriteAllText(Path.Combine(repoRoot, CSharpRelativePath), csharp);
            WriteAllText(Path.Combine(repoRoot, JavaScriptRelativePath), javascript);
            Console.WriteLine($"已生成 {CSharpRelativePath} 与 {JavaScriptRelativePath}（{commands.Count} 条命令）");
            return 0;
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine("桥接契约生成失败：" + ex.Message);
            return 1;
        }
    }

    private static string ResolveRepoRoot(string[] args)
    {
        for (var index = 0; index < args.Length; index++)
        {
            if (args[index] is "--repo-root" or "-r" && index + 1 < args.Length)
                return Path.GetFullPath(args[index + 1]);
        }
        return Directory.GetCurrentDirectory();
    }

    private static int ReadProtocolVersion(JsonObject root)
    {
        var node = root["protocolVersion"] ?? throw new InvalidOperationException("桥接协议必须包含 protocolVersion 和 commands。");
        return node.GetValue<int>();
    }

    private static string BuildCSharp(int protocolVersion, JsonObject commands)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("// 由 tools/OpenClawDebugger.ContractGen 依据 shared/WebUi/bridge-contract.json 生成，请勿手工编辑。");
        builder.AppendLine("using System.Collections.Generic;");
        builder.AppendLine();
        builder.AppendLine("namespace OpenClawDebugger;");
        builder.AppendLine();
        builder.AppendLine("internal static class BridgeContractGenerated");
        builder.AppendLine("{");
        builder.AppendLine($"    public const int ProtocolVersion = {protocolVersion};");
        builder.AppendLine("    public static readonly IReadOnlyDictionary<string, BridgeCommandDefinition> Commands =");
        builder.AppendLine("        new Dictionary<string, BridgeCommandDefinition>(StringComparer.Ordinal)");
        builder.AppendLine("        {");

        foreach (var (name, value) in commands)
        {
            var definition = value as JsonObject
                ?? throw new InvalidOperationException($"命令 {name} 的定义必须是对象。");
            var mode = ToCSharpString(definition["mode"]?.GetValue<string>());
            var domainNode = definition["domain"];
            var domain = domainNode is null ? "null" : ToCSharpString(domainNode.GetValue<string>());
            var timeout = definition["timeoutMs"]?.GetValue<int>() ?? 0;

            builder.AppendLine($"            [{ToCSharpString(name)}] = new BridgeCommandDefinition");
            builder.AppendLine("            {");
            builder.AppendLine($"                Mode = {mode},");
            builder.AppendLine($"                Domain = {domain},");
            builder.AppendLine($"                TimeoutMs = {timeout},");
            builder.AppendLine("                Payload = new Dictionary<string, string>(StringComparer.Ordinal)");
            builder.AppendLine("                {");
            if (definition["payload"] is JsonObject payload)
            {
                foreach (var (key, payloadValue) in payload)
                {
                    builder.AppendLine($"                    [{ToCSharpString(key)}] = {ToCSharpString(payloadValue?.GetValue<string>())},");
                }
            }
            builder.AppendLine("                }");
            builder.AppendLine("            },");
        }

        builder.AppendLine("        };");
        builder.AppendLine("}");
        return builder.ToString();
    }

    private static string BuildJavaScript(JsonObject contract)
    {
        var json = contract.ToJsonString(new JsonSerializerOptions { WriteIndented = true });
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("// 由 tools/OpenClawDebugger.ContractGen 依据 bridge-contract.json 生成，请勿手工编辑。");
        builder.AppendLine("(function () {");
        builder.AppendLine("  'use strict';");
        builder.AppendLine("  window.OpenClawBridgeContract = Object.freeze(" + json + ");");
        builder.AppendLine("})();");
        return builder.ToString();
    }

    private static string ToCSharpString(string? value)
    {
        if (value is null) return "null";
        return "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
    }

    private static void WriteAllText(string path, string content)
    {
        var directory = Path.GetDirectoryName(path);
        if (!string.IsNullOrEmpty(directory)) Directory.CreateDirectory(directory);
        File.WriteAllText(path, content, new UTF8Encoding(false));
    }
}
